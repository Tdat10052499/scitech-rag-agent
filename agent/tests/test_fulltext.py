def paper():
    return parse_paper_html(HTML, PAPER_ID, f"https://arxiv.org/html/{PAPER_ID}")


# --- Parsing and passages ----------------------------------------------------------------------


def test_parse_keeps_title_sections_math_and_captions_and_drops_the_rest() -> None:
    p = paper()
    assert p.title == "In-Context Retrieval-Augmented Language Models"
    headings = [s.heading for s in p.sections]
    assert headings == ["Front matter", "1 Introduction", "3 Experiments"]
    experiments = " ".join(p.sections[2].paragraphs)
    assert "stride s=4 gives" in experiments  # math as its alttext, once
    assert experiments.count("s=4") == 1
    assert "Table 1: Perplexity" in experiments
    text = " ".join(par for s in p.sections for par in s.paragraphs)
    for absent in ("not text", "Contents", "Ori Ram", "Footnote", "few-shot", "LaTeXML"):
        assert absent not in text


def test_parse_without_text_is_unavailable() -> None:
    with pytest.raises(FullTextUnavailable):
        parse_paper_html("<html><body><nav>menu</nav></body></html>", PAPER_ID, "u")


def test_split_passages_respects_the_word_limit_and_sections() -> None:
    passages = split_passages(paper(), max_words=12)
    assert all(len(p.text.split()) <= 12 for p in passages)
    assert passages[0].chunk_id == f"{PAPER_ID}#full-0"
    assert [p.chunk_index for p in passages] == list(range(len(passages)))
    assert {p.title for p in passages} == {
        f"In-Context Retrieval-Augmented Language Models (full text, section: {h})"
        for h in ("Front matter", "1 Introduction", "3 Experiments")
    }
    assert all(p.doc_id == PAPER_ID and p.source == "arxiv" for p in passages)


def test_rank_by_word_overlap_and_by_embedding() -> None:
    passages = split_passages(paper())
    best = rank_passages("what perplexity on WikiText-103?", PAPER_ID, passages, k=1)
    assert "Experiments" in best[0].title and best[0].score > 0
    embedder = FakeEmbedder()
    vectors = embedder.embed_passages([f"{p.title}. {p.text}" for p in passages])
    best = rank_passages("perplexity stride WikiText", PAPER_ID, passages, 1, embedder, vectors)
    assert "Experiments" in best[0].title


@pytest.mark.parametrize(
    "question",
    [f"Explain arXiv:{PAPER_ID} simply please", f"Giải thích dễ hiểu bài {PAPER_ID} cho tôi"],
)
def test_question_without_topic_words_gets_the_start_of_each_section(question: str) -> None:
    passages = split_passages(paper(), max_words=12)
    got = rank_passages(question, PAPER_ID, passages, k=3)
    assert [p.title.rsplit(": ", 1)[1].rstrip(")") for p in got] == [
        "Front matter",
        "1 Introduction",
        "3 Experiments",
    ]


# --- Fetching, cache, settings -----------------------------------------------------------------


class FakeHttp:
    def __init__(self, answers):
        self.answers = answers  # url -> (status, text) or an exception
        self.urls: list[str] = []

    def get(self, url):
        self.urls.append(url)
        answer = self.answers.get(url, (404, ""))
        if isinstance(answer, Exception):
            raise answer
        status, text = answer
        return SimpleNamespace(
            status_code=status, text=text, url=url, headers={"content-type": "text/html"}
        )


def test_fetcher_tries_the_next_url_and_reports_every_failure() -> None:
    urls = ("https://a/{id}", "https://b/{id}")
    http = FakeHttp({f"https://a/{PAPER_ID}": (404, ""), f"https://b/{PAPER_ID}": (200, HTML)})
    waits: list[float] = []
    fetcher = ArxivHtmlFetcher(urls, client=http, clock=lambda: 100.0, sleep=waits.append)
    got = fetcher.fetch(PAPER_ID)
    assert got.url == f"https://b/{PAPER_ID}" and http.urls[0] == f"https://a/{PAPER_ID}"
    assert waits == [3.0]  # the second request waited for arXiv's 3 s spacing
    http = FakeHttp({f"https://a/{PAPER_ID}": TimeoutError("slow")})
    with pytest.raises(FullTextUnavailable, match="TimeoutError.*HTTP 404"):
        ArxivHtmlFetcher(urls, client=http, min_interval=0).fetch(PAPER_ID)


class CountingFetcher:
    def __init__(self):
        self.calls = 0

    def fetch(self, arxiv_id):
        self.calls += 1
        return parse_paper_html(HTML, arxiv_id, f"https://arxiv.org/html/{arxiv_id}")


def test_reader_caches_papers_and_evicts_the_oldest() -> None:
    fetcher = CountingFetcher()
    reader = FullTextReader(fetcher, FakeEmbedder(), cache_size=1)
    _, cached = reader.passages(PAPER_ID, "perplexity", 2)
    assert cached is False
    passages, cached = reader.passages(PAPER_ID, "retrieval", 2)
    assert cached is True and fetcher.calls == 1 and len(passages) == 2
    reader.passages("2401.00001", "perplexity", 2)
    reader.passages(PAPER_ID, "perplexity", 2)
    assert fetcher.calls == 3


def test_reader_from_env_and_embedder_of() -> None:
    reader = reader_from_env(None, {"FULLTEXT_URLS": "https://x/{id}", "FULLTEXT_CACHE": "4"})
    assert reader.fetcher.urls == ("https://x/{id}",) and reader.cache_size == 4
    assert reader.embedder is None
    with pytest.raises(ValueError):
        reader_from_env(None, {"FULLTEXT_URLS": "https://x/"})
    with pytest.raises(ValueError):
        reader_from_env(None, {"FULLTEXT_TIMEOUT": "0"})
    embedder = FakeEmbedder()
    dense = DenseRetriever(InMemoryStore(), embedder)
    assert embedder_of(dense) is embedder
    assert embedder_of(SimpleNamespace(dense=dense)) is embedder
    assert embedder_of(InMemoryRetriever([])) is None


def test_factory_builds_the_reader_only_when_on(monkeypatch) -> None:
    env = {"LLM_BASE_URL": "http://llm.invalid/v1", "LLM_MODEL": "m", "AGENT_TRACES": "off"}
    monkeypatch.setattr(factory, "retriever_from_env", lambda env: InMemoryRetriever([]))
    assert isinstance(factory.agent_from_env(env).fulltext, FullTextReader)
    assert factory.agent_from_env({**env, "AGENT_FULLTEXT": "off"}).fulltext is None


# --- Agent -------------------------------------------------------------------------------------

ABSTRACT = ScoredChunk(
    chunk_id=f"{PAPER_ID}#0",
    doc_id=PAPER_ID,
    score=0.0,
    title="In-Context Retrieval-Augmented Language Models",
    text="language model grounding retrieval perplexity documents",
    source="arxiv",
    chunk_index=0,
    published_at="2023-01-31",
)


class BrokenFetcher:
    def fetch(self, arxiv_id):
        raise FullTextUnavailable(f"{arxiv_id}: HTTP 404")


def make_agent(fetcher, **config):
    tracer = ListTraceWriter()
    llm = FakeLLM(["In the Experiments section, perplexity drops [2].", "[]"])
    agent = Agent(
        InMemoryRetriever([ABSTRACT]),
        llm,
        AgentConfig(search_modes=True, fulltext=True, **config),
        tracer=tracer,
        fulltext=FullTextReader(fetcher),
    )
    return agent, llm, tracer


def test_arxiv_question_gets_the_abstract_and_full_text_passages() -> None:
    agent, llm, tracer = make_agent(CountingFetcher(), fulltext_top_k=2)
    list(agent.run("s1", f"What perplexity does {PAPER_ID} report on WikiText-103?"))
    user = llm.calls[0].messages[1]["content"]
    assert user.count("<source id=") == 3  # the abstract + 2 passages
    assert "(full text, section: 3 Experiments)" in user
    assert "Published: 2023-01-31" in user.split("full text")[1]  # passages carry the date
    search = tracer.traces[0]["search"]
    assert search["reasons"] == ["arxiv_id"] and search["fulltext"] == "read"
    assert f"{PAPER_ID}#full-" in " ".join(tracer.traces[0]["sources"])


def test_unreadable_full_text_keeps_the_abstract_only() -> None:
    agent, llm, tracer = make_agent(BrokenFetcher())
    list(agent.run("s1", f"What perplexity does {PAPER_ID} report?"))
    assert llm.calls[0].messages[1]["content"].count("<source id=") == 1
    assert tracer.traces[0]["search"]["fulltext"] == "unavailable"


def test_paper_outside_the_corpus_is_answered_from_its_full_text() -> None:
    agent, llm, tracer = make_agent(CountingFetcher())
    list(agent.run("s1", "What perplexity does 2501.99999 report on WikiText-103?"))
    assert "(full text, section:" in llm.calls[0].messages[1]["content"]
    assert tracer.traces[0]["search"]["fulltext"] == "read"


def test_fulltext_off_does_not_fetch() -> None:
    fetcher = CountingFetcher()
    agent, _, tracer = make_agent(fetcher)
    agent.config = AgentConfig(search_modes=True, fulltext=False)
    list(agent.run("s1", f"What perplexity does {PAPER_ID} report?"))
    assert fetcher.calls == 0 and tracer.traces[0]["search"]["fulltext"] is None
